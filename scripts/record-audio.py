"""Records every Father line and every server line with natural male neural voices (edge-tts),
after respelling the Latin for ecclesiastical pronunciation. Writes audio/*.mp3 and audio/index.js.
Run:  ~/AI/_scratch/claude/serve-mass/venv/bin/python scripts/record-audio.py <lines.json>"""
import json, sys, os, re, hashlib, subprocess, unicodedata, time
sys.path.insert(0, os.path.dirname(__file__))
from respell import respell

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'audio')
EDGE = os.path.join(os.path.dirname(sys.executable), 'edge-tts')
# Slow and distinct (Sam: the first takes ran words together).
FATHER = dict(voice='it-IT-DiegoNeural', rate='-28%', pitch='-8Hz')
SERVER = dict(voice='it-IT-GiuseppeMultilingualNeural', rate='-22%', pitch='-2Hz')
CLEAR = dict(voice='it-IT-GiuseppeMultilingualNeural', rate='-25%', pitch='-2Hz')

# What Father actually says when the cue only shows the end of it.
PRIEST_CONFITEOR = ("Confiteor Deo omnipotenti, beatae Mariae semper Virgini, beato Michaeli Archangelo, beato Joanni Baptistae, "
  "sanctis Apostolis Petro et Paulo, omnibus Sanctis, et vobis, fratres: quia peccavi nimis cogitatione, verbo et opere: "
  "mea culpa, mea culpa, mea maxima culpa. Ideo precor beatam Mariam semper Virginem, beatum Michaelem Archangelum, "
  "beatum Joannem Baptistam, sanctos Apostolos Petrum et Paulum, omnes Sanctos, et vos, fratres, orare pro me ad Dominum Deum nostrum.")
OVERRIDE = {'…et vos, fratres, orare pro me ad Dominum Deum nostrum.': PRIEST_CONFITEOR}

def key(text):  # must match app.js audioKey()
    out = []
    for w in text.split():
        w = ''.join(c for c in unicodedata.normalize('NFD', w.lower()) if unicodedata.category(c) != 'Mn')
        w = re.sub(r'[^a-z]', '', w.replace('æ', 'ae').replace('œ', 'oe').replace('j', 'i'))
        if w: out.append(w)
    return ' '.join(out)

def phrased(t):  # longer pauses at the Latin phrase breaks
    return re.sub(r'\s*[:;]\s*', '. ', t)

def word_by_word(t):  # a pause after every word, for learning each word distinctly
    return ', '.join(w.strip(',.:;?!') for w in t.split() if w.strip(',.:;?!')) + '.'

def record(text, who, cfg, shape=phrased):
    spoken = shape(respell(OVERRIDE.get(text, text)))
    name = who + '-' + hashlib.sha1((cfg['voice'] + cfg['rate'] + cfg['pitch'] + spoken).encode()).hexdigest()[:10] + '.mp3'
    path = os.path.join(OUT, name)
    if not os.path.exists(path):
        for attempt in range(4):
            r = subprocess.run([EDGE, '--voice', cfg['voice'], f"--rate={cfg['rate']}", f"--pitch={cfg['pitch']}", '--text', spoken, '--write-media', path], capture_output=True)
            if r.returncode == 0 and os.path.getsize(path) > 1000: break
            time.sleep(2 + 3 * attempt)
        else:
            raise SystemExit('failed: ' + spoken + '\n' + r.stderr.decode()[-300:])
    return name

os.makedirs(OUT, exist_ok=True)
lines = json.load(open(sys.argv[1]))
idx = {'father': {}, 'server': {}, 'clear': {}}
for t in lines['father']: idx['father'][key(t)] = record(t, 'f', FATHER)
for t in lines['server']: idx['server'][key(t)] = record(t, 's', SERVER)
for t in lines['server']:
    if len(t.split()) > 1: idx['clear'][key(t)] = record(t, 'c', CLEAR, word_by_word)
used = set(idx['father'].values()) | set(idx['server'].values()) | set(idx['clear'].values())
for f in os.listdir(OUT):
    if f.endswith('.mp3') and f not in used: os.remove(os.path.join(OUT, f))
with open(os.path.join(OUT, 'index.js'), 'w') as fh:
    fh.write('// generated by scripts/record-audio.py — Father: Diego, server: Giuseppe (edge-tts neural voices)\n')
    fh.write('window.MASS_AUDIO = ' + json.dumps(idx, ensure_ascii=False, indent=0) + ';\n')
print(len(idx['father']), 'father,', len(idx['server']), 'server,', len(idx['clear']), 'clear,', sum(os.path.getsize(os.path.join(OUT, f)) for f in used) // 1024, 'KB')
